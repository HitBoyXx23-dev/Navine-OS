section .text
font_draw_char:
    ; rdi=x, rsi=y, dl=char, ecx=color
    push rbx
    push r12
    push r13
    push r14
    push r15
    push rcx

    mov r12d, edi
    mov r13d, esi
    mov r14d, ecx
    movzx eax, dl

    cmp al, ' '
    je .out
    cmp al, 'a'
    jb .classify
    cmp al, 'z'
    ja .classify
    sub al, 32

.classify:
    cmp al, '0'
    jb .punct
    cmp al, '9'
    ja .letters
    sub al, '0'
    movzx eax, al
    imul eax, 7
    lea rbx, [digit_font + rax]
    jmp .draw

.letters:
    cmp al, 'A'
    jb .punct
    cmp al, 'Z'
    ja .punct
    sub al, 'A'
    movzx eax, al
    imul eax, 7
    lea rbx, [upper_font + rax]
    jmp .draw

.punct:
    cmp al, '.'
    je .dot
    cmp al, ','
    je .comma
    cmp al, ':'
    je .colon
    cmp al, '-'
    je .dash
    cmp al, '/'
    je .slash
    cmp al, '>'
    je .gt
    lea rbx, [punct_box]
    jmp .draw
.dot:
    lea rbx, [punct_dot]
    jmp .draw
.comma:
    lea rbx, [punct_comma]
    jmp .draw
.colon:
    lea rbx, [punct_colon]
    jmp .draw
.dash:
    lea rbx, [punct_dash]
    jmp .draw
.slash:
    lea rbx, [punct_slash]
    jmp .draw
.gt:
    lea rbx, [punct_gt]

.draw:
    xor r15d, r15d
.row:
    cmp r15d, 7
    jae .out
    movzx eax, byte [rbx + r15]
    xor r10d, r10d
.col:
    cmp r10d, 5
    jae .next_row
    mov r11d, 0x10
    mov ecx, r10d
    shr r11d, cl
    test eax, r11d
    jz .skip
    mov edi, r12d
    add edi, r10d
    mov esi, r13d
    add esi, r15d
    mov edx, r14d
    push rax
    call fb_put_pixel
    pop rax
.skip:
    inc r10d
    jmp .col
.next_row:
    inc r15d
    jmp .row

.out:
    pop rcx
    pop r15
    pop r14
    pop r13
    pop r12
    pop rbx
    ret

font_draw_string:
    ; rdi=x, rsi=y, rdx=str, ecx=color
    push rbx
    mov r8d, edi
    mov r9d, esi
    mov rbx, rdx
.loop:
    movzx eax, byte [rbx]
    test al, al
    jz .out
    mov edi, r8d
    mov esi, r9d
    mov dl, al
    push rbx
    push r8
    push r9
    call font_draw_char
    pop r9
    pop r8
    pop rbx
    add r8d, 7
    inc rbx
    jmp .loop
.out:
    pop rbx
    ret
