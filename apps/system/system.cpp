// Navine OS - Native C++ System Dashboard
// Freestanding binary loaded by the kernel at NAVAPP_LOAD_PHYS.

using u8 = unsigned char;
using u16 = unsigned short;
using u32 = unsigned int;
using u64 = unsigned long long;

namespace {
constexpr u64 FB_INFO_PHYS = 0x5000;
constexpr u16 PS2_DATA = 0x60;
constexpr u16 PS2_STATUS = 0x64;
constexpr u8 SC_ESC = 0x01;

struct FbInfo {
    u64 base;
    u32 width;
    u32 height;
    u32 pitch;
    u32 bpp;
};

inline u8 inb(u16 port) {
    u8 value;
    asm volatile("inb %1, %0" : "=a"(value) : "Nd"(port));
    return value;
}

inline bool key_available() {
    return (inb(PS2_STATUS) & 1) != 0;
}

inline u8 read_key() {
    return inb(PS2_DATA);
}

inline FbInfo& fb() {
    return *reinterpret_cast<FbInfo*>(FB_INFO_PHYS);
}

void rect(int x, int y, int w, int h, u32 color) {
    FbInfo& f = fb();
    if (f.bpp != 32 || f.base == 0) return;
    if (x < 0) { w += x; x = 0; }
    if (y < 0) { h += y; y = 0; }
    if (x + w > static_cast<int>(f.width)) w = static_cast<int>(f.width) - x;
    if (y + h > static_cast<int>(f.height)) h = static_cast<int>(f.height) - y;
    if (w <= 0 || h <= 0) return;

    for (int row = 0; row < h; ++row) {
        auto* dst = reinterpret_cast<u32*>(f.base + static_cast<u64>(y + row) * f.pitch + x * 4);
        for (int col = 0; col < w; ++col) dst[col] = color;
    }
}

void glyph(int x, int y, char c, u32 color) {
    static constexpr u8 font[37][7] = {
        {0x0E,0x11,0x13,0x15,0x19,0x11,0x0E}, {0x04,0x0C,0x04,0x04,0x04,0x04,0x0E},
        {0x0E,0x11,0x01,0x02,0x04,0x08,0x1F}, {0x1E,0x01,0x01,0x0E,0x01,0x01,0x1E},
        {0x02,0x06,0x0A,0x12,0x1F,0x02,0x02}, {0x1F,0x10,0x1E,0x01,0x01,0x11,0x0E},
        {0x06,0x08,0x10,0x1E,0x11,0x11,0x0E}, {0x1F,0x01,0x02,0x04,0x08,0x08,0x08},
        {0x0E,0x11,0x11,0x0E,0x11,0x11,0x0E}, {0x0E,0x11,0x11,0x0F,0x01,0x02,0x0C},
        {0x0E,0x11,0x11,0x1F,0x11,0x11,0x11}, {0x1E,0x11,0x11,0x1E,0x11,0x11,0x1E},
        {0x0E,0x11,0x10,0x10,0x10,0x11,0x0E}, {0x1E,0x11,0x11,0x11,0x11,0x11,0x1E},
        {0x1F,0x10,0x10,0x1E,0x10,0x10,0x1F}, {0x1F,0x10,0x10,0x1E,0x10,0x10,0x10},
        {0x0E,0x11,0x10,0x17,0x11,0x11,0x0F}, {0x11,0x11,0x11,0x1F,0x11,0x11,0x11},
        {0x0E,0x04,0x04,0x04,0x04,0x04,0x0E}, {0x07,0x02,0x02,0x02,0x12,0x12,0x0C},
        {0x11,0x12,0x14,0x18,0x14,0x12,0x11}, {0x10,0x10,0x10,0x10,0x10,0x10,0x1F},
        {0x11,0x1B,0x15,0x15,0x11,0x11,0x11}, {0x11,0x19,0x15,0x13,0x11,0x11,0x11},
        {0x0E,0x11,0x11,0x11,0x11,0x11,0x0E}, {0x1E,0x11,0x11,0x1E,0x10,0x10,0x10},
        {0x0E,0x11,0x11,0x11,0x15,0x12,0x0D}, {0x1E,0x11,0x11,0x1E,0x14,0x12,0x11},
        {0x0F,0x10,0x10,0x0E,0x01,0x01,0x1E}, {0x1F,0x04,0x04,0x04,0x04,0x04,0x04},
        {0x11,0x11,0x11,0x11,0x11,0x11,0x0E}, {0x11,0x11,0x11,0x11,0x11,0x0A,0x04},
        {0x11,0x11,0x11,0x15,0x15,0x15,0x0A}, {0x11,0x11,0x0A,0x04,0x0A,0x11,0x11},
        {0x11,0x11,0x0A,0x04,0x04,0x04,0x04}, {0x1F,0x01,0x02,0x04,0x08,0x10,0x1F},
        {0x00,0x00,0x00,0x00,0x00,0x00,0x00}
    };
    int idx = 36;
    if (c >= '0' && c <= '9') idx = c - '0';
    if (c >= 'A' && c <= 'Z') idx = 10 + (c - 'A');
    if (c >= 'a' && c <= 'z') idx = 10 + (c - 'a');
    for (int row = 0; row < 7; ++row) {
        for (int col = 0; col < 5; ++col) {
            if (font[idx][row] & (1 << (4 - col))) rect(x + col * 2, y + row * 2, 2, 2, color);
        }
    }
}

void text(int x, int y, const char* s, u32 color) {
    while (*s) {
        if (*s == ' ') { x += 10; ++s; continue; }
        glyph(x, y, *s++, color);
        x += 12;
    }
}

void draw_dashboard() {
    FbInfo& f = fb();
    rect(0, 0, static_cast<int>(f.width), static_cast<int>(f.height), 0xFF07111F);
    rect(0, 0, static_cast<int>(f.width), 42, 0xFF0B6FD3);
    text(24, 14, "NAVINE SYSTEM", 0xFFFFFFFF);
    rect(64, 90, 896, 520, 0xFF101820);
    rect(64, 90, 8, 520, 0xFF00D7FF);
    text(104, 126, "CXX NATIVE APP", 0xFF00D7FF);
    text(104, 176, "FRAMEBUFFER OK", 0xFFFFFFFF);
    text(104, 216, "PS2 INPUT OK", 0xFFFFFFFF);
    text(104, 256, "FREESTANDING MODE", 0xFFFFFFFF);
    text(104, 330, "PRESS ESC TO RETURN", 0xFFB8D7F0);
    rect(104, 420, 720, 26, 0xFF172A3C);
    rect(104, 420, 520, 26, 0xFF0B6FD3);
    text(126, 426, "SYSTEM HEALTH", 0xFFFFFFFF);
}
}

extern "C" void _start() {
    draw_dashboard();
    for (;;) {
        if (key_available()) {
            u8 key = read_key();
            if (key == SC_ESC) return;
        }
        asm volatile("pause");
    }
}
